def _yaml_quote(text: str) -> str:
    """Return `text` as a double-quoted YAML scalar."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _lint_rules(glossary: Glossary) -> str:
    """Return the generated `custom_rules` entries as YAML.

    Every rule carries the files that still hold a backlog for it as
    `excluded`, because CI lints with `--strict` and a warning in a legacy file
    would block every commit. Those files stay covered by the budget in
    `.naming-budget.json`, which forbids growth; every other file — including
    every file added tomorrow — is gated here, in the editor, while typing.

    A pattern's exclusions are computed from its regex alone, not from this
    script's findings. `scan` reports a spelling that a term already rejects
    only once, under that term — but SwiftLint has no such rule, so
    `config_suffix` sees every `KeyConfig` too, and would fire in all 22 of its
    files if only the two `keyConfig` ones were excluded.
    """
    files = swift_files()
    carriers: dict[str, set[str]] = {}
    for finding in scan(glossary, files):
        carriers.setdefault(finding.rejected, set()).add(finding.path)
    carriers.update(_pattern_carriers(glossary, files))

    entries: list[tuple[str, str, str, str, set[str]]] = []
    for term in glossary.terms:
        for alias in term.rejected:
            entries.append(
                (
                    f"glossary_{_rule_id(alias)}",
                    f"Glossary: {alias}",
                    rf"\b{re.escape(alias)}\b",
                    f"`{alias}` is rejected — the glossary term is `{term.name}` (docs/GLOSSARY.md).",
                    carriers.get(alias, set()) | set(glossary.exceptions.get(alias, ())),
                )
            )
    for pattern in glossary.patterns:
        if not pattern.checks_identifiers:
            continue
        entries.append(
            (
                f"glossary_{pattern.id}",
                f"Glossary: {pattern.id.replace('_', ' ')}",
                _regex_with_allowed(pattern.regex, pattern.allowed),
                f"{pattern.rationale} Write {pattern.replacement} instead (docs/GLOSSARY.md).",
                carriers.get(pattern.id, set()) | set(glossary.exceptions.get(pattern.id, ())),
            )
        )

    lines: list[str] = []
    for rule_id, name, regex, message, excluded in sorted(entries):
        lines.append(f"  {rule_id}:")
        lines.append(f"    name: {_yaml_quote(name)}")
        lines.append(f"    regex: {_yaml_quote(regex)}")
        lines.append("    match_kinds: [identifier]")
        lines.append(f"    message: {_yaml_quote(message)}")
        lines.append("    severity: error")
        if excluded:
            lines.append("    excluded:")
            for path in sorted(excluded):
                lines.append(f"      - {_yaml_quote(re.escape(path))}")
    return "\n".join(lines)


def _pattern_carriers(glossary: Glossary, files: list[Path], root: Path = REPO_ROOT) -> dict[str, set[str]]:
    """Return, per pattern, every file its regex matches — dedup rules aside."""
    carriers: dict[str, set[str]] = {}
    compiled = [(pattern, pattern.compiled()) for pattern in glossary.patterns if pattern.checks_identifiers]
    for file in files:
        relative = str(file.relative_to(root))
        code = strip_noncode(file.read_text(encoding="utf-8", errors="replace"))
        for pattern, regex in compiled:
            if regex.search(code):
                carriers.setdefault(pattern.id, set()).add(relative)
    return carriers


def _rule_id(alias: str) -> str:
    """Return a snake_case SwiftLint rule id for a rejected spelling."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", alias).lower()


def mode_sync_lint(glossary: Glossary, check_only: bool) -> int:
    """Rewrite (or verify) the generated block in `.swiftlint.yml`."""
    original = SWIFTLINT_FILE.read_text(encoding="utf-8")
    if YAML_MARKER_START not in original or YAML_MARKER_END not in original:
        _fail(f"{SWIFTLINT_FILE.name}: no generated block")
    head, rest = original.split(YAML_MARKER_START, 1)
    _, tail = rest.split(YAML_MARKER_END, 1)
    updated = f"{head}{YAML_MARKER_START}\n{_lint_rules(glossary)}\n{YAML_MARKER_END}{tail}"

    if updated == original:
        print(f"{SWIFTLINT_FILE.name} is up to date.")
        return 0
    if check_only:
        print(
            f"error: {SWIFTLINT_FILE.name} is stale — run `python3 scripts/check_naming.py sync-lint`",
            file=sys.stderr,
        )
        return 1
    SWIFTLINT_FILE.write_text(updated, encoding="utf-8")
    print(f"Rewrote the generated custom rules in {SWIFTLINT_FILE.name}.")
    return 0


