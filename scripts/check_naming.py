#!/usr/bin/env python3
"""Per-file budget for rejected names: freeze the naming backlog, refuse growth.

`glossary.toml` holds one term per domain concept together with the spellings
that term replaces, plus shape rules for names nobody has written yet. This
script reads that file and reports every identifier in the Swift sources that
contradicts it.

A name already used in a hundred places cannot be fixed by adding a rule, and
excluding the files that carry it would exempt the names written tomorrow along
with the ones written yesterday. So the backlog is a budget: a file may not
exceed the number of rejected names it carries today, and a file that is not in
the budget may not carry a single one. The budget only ever shrinks. Once the
last entry reaches zero, `.naming-budget.json` is deleted and the check becomes
"no rejected spelling anywhere".

Only identifiers are counted. Comments and string literals are removed before
matching, so prose quoting a rejected spelling costs nothing — but the contents
of a string interpolation are kept, because `"\\(slotId)"` really is a reference
to the identifier. Where a rejected spelling is the correct name after all,
`[[exception]]` in `glossary.toml` records it together with its reason.

Five modes:

``check``
    Count today's findings and exit non-zero when a file is over its budget, or
    when a file with no budget has a finding at all. This is what CI runs.

``list``
    Print the findings themselves, for one path or for the whole tree.

``update``
    Rewrite the budget from today's counts. Run this after a rename, so the
    lower number is the one that has to be held. It refuses to record a count
    that grew unless ``--allow-raise`` says so, which is for the two ways a
    count rises without anyone writing a rejected name: a file moved and took
    its backlog along, or the glossary gained a term and the tree already
    spelled it the old way.

``render``
    Rewrite the generated sections of `docs/GLOSSARY.md` from the glossary.
    Those two tables are this script's input and output; a hand-maintained
    second copy of them would drift, and a rejected spelling that is listed but
    not enforced reads as enforced. ``--check`` verifies instead of writing.

``sync-lint``
    Rewrite the generated `custom_rules` block in `.swiftlint.yml`, so the rules
    fire in Xcode while typing rather than only in CI. Each rule excludes the
    files that still carry a backlog for it, because CI lints with ``--strict``;
    those files stay covered by the budget. ``--check`` verifies instead of
    writing.

Usage:

    python3 scripts/check_naming.py check
    python3 scripts/check_naming.py list wurstfingerKeyboard/Runtime
    python3 scripts/check_naming.py list --statistics
    python3 scripts/check_naming.py update
    python3 scripts/check_naming.py render --check
    python3 scripts/check_naming.py sync-lint --check
"""

from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import dataclass
import json
from pathlib import Path
import re
import sys
import tomllib

REPO_ROOT = Path(__file__).resolve().parent.parent
GLOSSARY_FILE = REPO_ROOT / "glossary.toml"
BUDGET_FILE = REPO_ROOT / ".naming-budget.json"
GLOSSARY_DOC = REPO_ROOT / "docs" / "GLOSSARY.md"
SWIFTLINT_FILE = REPO_ROOT / ".swiftlint.yml"

SCANNED = ("wurstfinger", "wurstfingerKeyboard", "wurstfingerTests", "wurstfingerUITests")

MARKER_START = "<!-- generated by scripts/check_naming.py — do not edit: {name} -->"
MARKER_END = "<!-- /generated: {name} -->"
YAML_MARKER_START = "  # --- generated by scripts/check_naming.py — do not edit ---"
YAML_MARKER_END = "  # --- end generated ---"


# ---------------------------------------------------------------------------
# The glossary
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class Term:
    """One canonical name and the spellings it replaces."""

    name: str
    zone: str
    definition: str
    rejected: tuple[str, ...]
    note: str


@dataclass(frozen=True)
class Pattern:
    """A shape rule: a regex over identifiers, with an allow-list.

    Terms catch the rejected spellings that exist today. Patterns catch the
    ones nobody has written yet — a `FooConfig` added next month matches the
    suffix rule without anyone having to extend the term list first.
    """

    id: str
    regex: str
    replacement: str
    rationale: str
    allowed: tuple[str, ...]
    applies_to: tuple[str, ...]

    def compiled(self) -> re.Pattern[str]:
        """Return the regex, with the allow-list turned into a lookahead."""
        return re.compile(_regex_with_allowed(self.regex, self.allowed))

    @property
    def checks_identifiers(self) -> bool:
        """Return whether this rule reads identifiers in the source."""
        return "identifier" in self.applies_to

    @property
    def checks_filenames(self) -> bool:
        """Return whether this rule reads file names.

        `GeometryUtils.swift` holds free extensions and declares no type, so a
        rule that only reads identifiers never sees the vague name at all.
        """
        return "filename" in self.applies_to


@dataclass(frozen=True)
class Glossary:
    """The parsed contents of `glossary.toml`."""

    terms: tuple[Term, ...]
    patterns: tuple[Pattern, ...]
    exceptions: dict[str, tuple[str, ...]]
    exception_reasons: dict[str, str]

    @property
    def aliases(self) -> dict[str, str]:
        """Map every rejected spelling to the term that replaces it."""
        return {alias: term.name for term in self.terms for alias in term.rejected}


def _regex_with_allowed(regex: str, allowed: tuple[str, ...]) -> str:
    """Return `regex` guarded by a negative lookahead for the allowed names.

    A pattern and its allow-list become one string rather than two things that
    have to be kept in step.
    """
    if not allowed:
        return regex
    alternatives = "|".join(re.escape(name) for name in sorted(allowed))
    return f"(?!(?:{alternatives})\\b){regex}"


def load_glossary(path: Path = GLOSSARY_FILE) -> Glossary:
    """Return the glossary, refusing a source that contradicts itself."""
    with path.open("rb") as handle:
        raw = tomllib.load(handle)

    terms = tuple(
        Term(
            name=entry["name"],
            zone=entry["zone"],
            definition=entry["definition"],
            rejected=tuple(entry.get("rejected", ())),
            note=entry.get("note", ""),
        )
        for entry in raw.get("term", ())
    )
    patterns = tuple(
        Pattern(
            id=entry["id"],
            regex=entry["regex"],
            replacement=entry["replacement"],
            rationale=entry.get("rationale", ""),
            allowed=tuple(entry.get("allowed", ())),
            applies_to=tuple(entry.get("applies_to", ("identifier",))),
        )
        for entry in raw.get("pattern", ())
    )

    canonical = {term.name for term in terms}
    seen_alias: dict[str, str] = {}
    for term in terms:
        if term.zone not in ("A", "B", "C"):
            _fail(f"{path.name}: `{term.name}` has zone `{term.zone}`, expected A, B or C")
        for alias in term.rejected:
            if alias in canonical:
                _fail(f"{path.name}: `{alias}` is both a term and rejected by `{term.name}`")
            if alias in seen_alias:
                _fail(f"{path.name}: `{alias}` is rejected by both `{seen_alias[alias]}` and `{term.name}`")
            seen_alias[alias] = term.name

    pattern_ids = {pattern.id for pattern in patterns}
    if len(pattern_ids) != len(patterns):
        _fail(f"{path.name}: two patterns share an id")
    for pattern in patterns:
        try:
            re.compile(_regex_with_allowed(pattern.regex, pattern.allowed))
        except re.error as error:
            _fail(f"{path.name}: pattern `{pattern.id}` has an invalid regex: {error}")
        unknown = set(pattern.applies_to) - {"identifier", "filename"}
        if unknown:
            _fail(f"{path.name}: pattern `{pattern.id}` applies to {sorted(unknown)}, expected identifier or filename")
        if not pattern.applies_to:
            _fail(f"{path.name}: pattern `{pattern.id}` applies to nothing")

    exceptions: dict[str, tuple[str, ...]] = {}
    reasons: dict[str, str] = {}
    for entry in raw.get("exception", ()):
        name = entry["name"]
        if name not in seen_alias and name not in pattern_ids:
            _fail(f"{path.name}: exception for `{name}`, which is neither a rejected spelling nor a pattern id")
        if not entry.get("reason"):
            _fail(f"{path.name}: exception for `{name}` has no reason")
        exceptions[name] = tuple(entry["paths"])
        reasons[name] = entry["reason"]

    return Glossary(terms=terms, patterns=patterns, exceptions=exceptions, exception_reasons=reasons)


def _fail(message: str) -> None:
    """Abort with a message; a self-contradicting glossary is a hard error."""
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(2)


