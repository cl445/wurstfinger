@dataclass(frozen=True)
class Finding:
    """One identifier that contradicts the glossary."""

    path: str
    line: int
    name: str
    rejected: str
    replacement: str

    def __str__(self) -> str:
        """Return the finding as a `file:line: message` line."""
        return f"{self.path}:{self.line}: `{self.name}` is rejected, use {self.replacement}"


def _excepted(glossary: Glossary, key: str, path: str) -> bool:
    """Return whether `key` is waived for `path` by an `[[exception]]`."""
    return any(path == waived or path.startswith(f"{waived}/") for waived in glossary.exceptions.get(key, ()))


def scan(glossary: Glossary, files: list[Path], root: Path = REPO_ROOT) -> list[Finding]:
    """Return every finding in `files`, in file then line order."""
    aliases = glossary.aliases
    alias_patterns = {alias: re.compile(rf"\b{re.escape(alias)}\b") for alias in aliases}
    compiled_patterns = [(pattern, pattern.compiled()) for pattern in glossary.patterns]
    findings: list[Finding] = []

    for file in files:
        relative = str(file.relative_to(root))
        code = strip_noncode(file.read_text(encoding="utf-8", errors="replace"))
        starts = _line_starts(code)

        for pattern, regex in compiled_patterns:
            if not pattern.checks_filenames or _excepted(glossary, pattern.id, relative):
                continue
            if regex.search(file.stem):
                findings.append(Finding(relative, 1, file.name, pattern.id, pattern.replacement))

        for alias, regex in alias_patterns.items():
            if _excepted(glossary, alias, relative):
                continue
            replacement = aliases[alias]
            for match in regex.finditer(code):
                findings.append(
                    Finding(relative, _line_of(starts, match.start()), match.group(0), alias, f"`{replacement}`")
                )

        for pattern, regex in compiled_patterns:
            if not pattern.checks_identifiers or _excepted(glossary, pattern.id, relative):
                continue
            for match in regex.finditer(code):
                # A spelling that a term already rejects is reported once, under
                # that term, which names the concrete replacement. Counting it
                # twice would inflate every budget it appears in.
                if match.group(0) in aliases:
                    continue
                findings.append(
                    Finding(relative, _line_of(starts, match.start()), match.group(0), pattern.id, pattern.replacement)
                )

    return sorted(findings, key=lambda finding: (finding.path, finding.line, finding.name))


def _line_starts(text: str) -> list[int]:
    """Return the offset of every line start, for offset-to-line lookups."""
    starts = [0]
    for index, character in enumerate(text):
        if character == "\n":
            starts.append(index + 1)
    return starts


def _line_of(starts: list[int], offset: int) -> int:
    """Return the 1-based line number containing `offset`."""
    low, high = 0, len(starts) - 1
    while low < high:
        middle = (low + high + 1) // 2
        if starts[middle] <= offset:
            low = middle
        else:
            high = middle - 1
    return low + 1


def counts_by_file(findings: list[Finding]) -> dict[str, int]:
    """Return how many findings each file carries."""
    counter = Counter(finding.path for finding in findings)
    return {path: counter[path] for path in sorted(counter)}


def load_budget() -> dict[str, int]:
    """Return the recorded budget, or an empty one once the file is gone."""
    if not BUDGET_FILE.exists():
        return {}
    return json.loads(BUDGET_FILE.read_text(encoding="utf-8"))


