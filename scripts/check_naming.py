def _render_rejected(glossary: Glossary) -> str:
    """Return the Markdown table for GLOSSARY.md §7."""
    rows = [(f"`{alias}`", f"`{term.name}`") for term in glossary.terms for alias in term.rejected]
    rows += [(pattern.id.replace("_", " "), pattern.replacement) for pattern in glossary.patterns]
    lines = ["| Avoid | Write instead |", "| --- | --- |"]
    for avoid, instead in sorted(rows, key=lambda row: row[0].strip("`").lower()):
        lines.append(f"| {avoid} | {instead} |")
    return "\n".join(lines)


def _render_backlog(glossary: Glossary) -> str:
    """Return the Markdown table for GLOSSARY.md §8.

    Generated from the budget rather than hand-listed, so the section is
    exhaustive by construction instead of ending in "not exhaustive".
    """
    findings = scan(glossary, swift_files())
    counter = Counter(finding.rejected for finding in findings)
    if not counter:
        return "The backlog is empty: no source file carries a rejected spelling."

    pattern_ids = {pattern.id for pattern in glossary.patterns}
    replacement = {alias: f"`{name}`" for alias, name in glossary.aliases.items()}
    replacement.update({pattern.id: pattern.replacement for pattern in glossary.patterns})
    files = {name: len({f.path for f in findings if f.rejected == name}) for name in counter}

    lines = ["| Legacy spelling | Replacement | Sites | Files |", "| --- | --- | --- | --- |"]
    for name, count in sorted(counter.items(), key=lambda item: (-item[1], item[0])):
        shown = name.replace("_", " ") if name in pattern_ids else f"`{name}`"
        lines.append(f"| {shown} | {replacement[name]} | {count} | {files[name]} |")
    lines.append(f"| **total** | | **{sum(counter.values())}** | **{len(counts_by_file(findings))}** |")
    return "\n".join(lines)


def _render_exceptions(glossary: Glossary) -> str:
    """Return the Markdown table of path-scoped waivers."""
    if not glossary.exceptions:
        return "No waivers are recorded."
    lines = ["| Spelling | Where | Why |", "| --- | --- | --- |"]
    for name in sorted(glossary.exceptions):
        where = "<br>".join(f"`{path}`" for path in glossary.exceptions[name])
        lines.append(f"| `{name}` | {where} | {glossary.exception_reasons[name]} |")
    return "\n".join(lines)


def _replace_block(text: str, name: str, body: str) -> str:
    """Return `text` with the named generated block replaced by `body`."""
    start = MARKER_START.format(name=name)
    end = MARKER_END.format(name=name)
    if start not in text or end not in text:
        _fail(f"{GLOSSARY_DOC.name}: no generated block named `{name}`")
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{start}\n\n{body}\n\n{end}{tail}"


def mode_render(glossary: Glossary, check_only: bool) -> int:
    """Rewrite (or verify) the generated tables in `docs/GLOSSARY.md`."""
    original = GLOSSARY_DOC.read_text(encoding="utf-8")
    updated = original
    for name, body in (
        ("rejected", _render_rejected(glossary)),
        ("backlog", _render_backlog(glossary)),
        ("exceptions", _render_exceptions(glossary)),
    ):
        updated = _replace_block(updated, name, body)

    if updated == original:
        print(f"{GLOSSARY_DOC.relative_to(REPO_ROOT)} is up to date.")
        return 0
    if check_only:
        print(
            f"error: {GLOSSARY_DOC.relative_to(REPO_ROOT)} is stale — "
            "run `python3 scripts/check_naming.py render`",
            file=sys.stderr,
        )
        return 1
    GLOSSARY_DOC.write_text(updated, encoding="utf-8")
    print(f"Rewrote the generated sections of {GLOSSARY_DOC.relative_to(REPO_ROOT)}.")
    return 0


