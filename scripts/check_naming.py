# Modes
# ---------------------------------------------------------------------------


def budget_drift(
    actual: dict[str, int], budget: dict[str, int]
) -> tuple[list[str], list[str], list[str]]:
    """Return the three ways a live count and its recorded budget disagree.

    `over` grew past what was recorded, `stale` lost everything it carried,
    `slack` lost some of it. All three are failures: the first is a new
    rejected name, the other two are an unrecorded shrink, which leaves the
    budget holding a slot the tree no longer needs.

    Split out of `mode_check` so the rule can be tested without a source tree.
    """
    over = sorted(path for path, count in actual.items() if count > budget.get(path, 0))
    stale = sorted(set(budget) - set(actual))
    slack = sorted(
        path for path, count in actual.items() if path in budget and count < budget[path]
    )
    return over, stale, slack


def mode_check(glossary: Glossary) -> int:
    """Fail when a file's count and its recorded budget have drifted apart.

    Both directions fail, because a ratchet that only catches growth is not
    one: a file that drops from 14 to 13 while the budget still reads 14
    leaves a slot open, and the next rejected name walks into it without CI
    noticing. Holding the lower number is what makes the budget mean
    something, so a shrink has to be recorded rather than merely allowed.
    """
    findings = scan(glossary, swift_files())
    actual = counts_by_file(findings)
    budget = load_budget()

    over_paths, stale, slack_paths = budget_drift(actual, budget)
    over = [
        f"{path}: {actual[path]} rejected name{'' if actual[path] == 1 else 's'}, "
        f"budget {budget.get(path, 0)}"
        for path in over_paths
    ]

    if over:
        by_file: dict[str, list[Finding]] = {}
        for finding in findings:
            by_file.setdefault(finding.path, []).append(finding)
        print("Rejected names beyond the recorded budget:\n", file=sys.stderr)
        for line in over:
            path = line.split(":", 1)[0]
            print(f"  {line}", file=sys.stderr)
            for finding in by_file[path]:
                print(f"    {finding}", file=sys.stderr)
        print(
            "\nThe budget records the backlog as it stood; it may shrink, never grow."
            "\nRename the new occurrence, or add an [[exception]] to glossary.toml with a reason.",
            file=sys.stderr,
        )
        return 1

    if stale:
        print("Budget entries that no longer carry anything — run `update`:", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        return 1

    # A file that lost some — but not all — of its backlog. `stale` above only
    # catches the count reaching zero, which leaves the partial case as free
    # headroom for the next rejected name.
    if slack_paths:
        print("Budget entries that are now too generous — run `update`:", file=sys.stderr)
        for path in slack_paths:
            print(f"  {path}: {actual[path]} rejected names, budget {budget[path]}", file=sys.stderr)
        print(
            "\nA name was removed without recording it. Until the budget is"
            "\nlowered, that slot stays open for the next one.",
            file=sys.stderr,
        )
        return 1

    total = sum(actual.values())
    print(f"OK — {total} rejected name{'s' if total != 1 else ''} in {len(actual)} files, all within budget.")
    return 0


def mode_list(glossary: Glossary, scope: Path | None, statistics: bool) -> int:
    """Print the findings, or a per-spelling tally with `--statistics`."""
    findings = scan(glossary, swift_files(scope=scope))
    if statistics:
        counter = Counter(finding.rejected for finding in findings)
        width = max((len(name) for name in counter), default=0)
        for name, count in sorted(counter.items(), key=lambda item: (-item[1], item[0])):
            print(f"{count:5}  {name:<{width}}")
        print(f"{sum(counter.values()):5}  total")
        return 0
    for finding in findings:
        print(finding)
    return 0


def mode_update(glossary: Glossary, allow_raise: bool) -> int:
    """Rewrite the budget from today's counts, refusing a silent increase."""
    actual = counts_by_file(scan(glossary, swift_files()))
    previous = load_budget()

    grown = {
        path: (previous[path], count)
        for path, count in actual.items()
        if path in previous and count > previous[path]
    }
    added = {path: count for path, count in actual.items() if path not in previous}
    if not allow_raise and (grown or added):
        for path, (was, now) in sorted(grown.items()):
            print(f"error: {path} grew from {was} to {now}", file=sys.stderr)
        for path, count in sorted(added.items()):
            print(f"error: {path} is not in the budget but carries {count}", file=sys.stderr)
        print(
            "\nThe budget only shrinks. Pass --allow-raise if a file moved and took its"
            "\nbacklog along, or if the glossary gained a term the tree already spelled"
            "\nthe old way.",
            file=sys.stderr,
        )
        return 1

    if not actual:
        if BUDGET_FILE.exists():
            BUDGET_FILE.unlink()
            print("The backlog is empty — removed .naming-budget.json.")
        else:
            print("The backlog is empty.")
        return 0

    BUDGET_FILE.write_text(json.dumps(actual, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    removed = sorted(set(previous) - set(actual))
    shrunk = sum(previous.get(path, 0) - count for path, count in actual.items() if count < previous.get(path, 0))
    print(f"Recorded {sum(actual.values())} rejected names in {len(actual)} files.")
    if shrunk or removed:
        print(f"  {shrunk} fewer than before; {len(removed)} file(s) now clean.")
    return 0


