def strip_noncode(source: str) -> str:
    """Return `source` with comments and string literals blanked out.

    Newlines are preserved so line numbers survive. The contents of a string
    interpolation are kept: `"\\(slotId)"` is a reference to the identifier,
    not prose about it. Raw string delimiters (`#"…"#`) are honoured, since
    inside them `\\(` is not an interpolation.
    """
    out: list[str] = []
    index = 0
    length = len(source)

    def keep_newlines(text: str) -> str:
        """Blank `text` while keeping its newlines, so line numbers survive."""
        return "".join(character if character == "\n" else " " for character in text)

    while index < length:
        character = source[index]

        if source.startswith("//", index):
            end = source.find("\n", index)
            end = length if end < 0 else end
            out.append(keep_newlines(source[index:end]))
            index = end
            continue

        if source.startswith("/*", index):
            depth, cursor = 1, index + 2
            while cursor < length and depth:
                if source.startswith("/*", cursor):
                    depth, cursor = depth + 1, cursor + 2
                elif source.startswith("*/", cursor):
                    depth, cursor = depth - 1, cursor + 2
                else:
                    cursor += 1
            out.append(keep_newlines(source[index:cursor]))
            index = cursor
            continue

        hashes = 0
        while index + hashes < length and source[index + hashes] == "#":
            hashes += 1
        quote_at = index + hashes
        if quote_at < length and source[quote_at] == '"':
            consumed, text = _read_string(source, index, hashes)
            out.append(text)
            index = consumed
            continue

        out.append(character)
        index += 1

    return "".join(out)


def _read_string(source: str, start: int, hashes: int) -> tuple[int, str]:
    """Consume one string literal from `start`; return (end index, replacement).

    The replacement blanks the literal but keeps interpolated expressions and
    every newline, so both line numbers and interpolated identifiers survive.
    An interpolated expression is stripped in turn, so a comment or a nested
    literal inside it does not re-enter the scan as code.
    """
    fence = "#" * hashes
    triple = source.startswith('"""', start + hashes)
    closing = f'"""{fence}' if triple else f'"{fence}'
    escape = f"\\{fence}"
    index = start + hashes + (3 if triple else 1)
    pieces: list[str] = [" " * (index - start)]
    length = len(source)

    while index < length:
        if source.startswith(closing, index):
            index += len(closing)
            pieces.append(" " * len(closing))
            break
        if source.startswith(escape + "(", index):
            depth, cursor = 1, index + len(escape) + 1
            while cursor < length and depth:
                if source[cursor] == "(":
                    depth += 1
                elif source[cursor] == ")":
                    depth -= 1
                cursor += 1
            pieces.append(" " * (len(escape) + 1))
            # The expression is code, but it can carry non-code of its own: a
            # comment, or a nested literal whose *contents* are prose again.
            # Stripping it recursively keeps the identifiers and drops the
            # rest; `strip_noncode` preserves length, so offsets still line up.
            pieces.append(strip_noncode(source[index + len(escape) + 1 : cursor - 1]))
            pieces.append(" ")
            index = cursor
            continue
        if source.startswith(escape, index):
            pieces.append(" " * (len(escape) + 1))
            index += len(escape) + 1
            continue
        pieces.append("\n" if source[index] == "\n" else " ")
        index += 1

    return index, "".join(pieces)


def swift_files(root: Path = REPO_ROOT, scope: Path | None = None) -> list[Path]:
    """Return the Swift sources to scan, sorted, honouring an optional scope."""
    files: list[Path] = []
    for directory in SCANNED:
        base = root / directory
        if not base.is_dir():
            continue
        files.extend(base.rglob("*.swift"))
    if scope is not None:
        resolved = scope.resolve()
        files = [path for path in files if resolved == path or resolved in path.parents]
    return sorted(files)


