def main(argv: list[str] | None = None) -> int:
    """Parse arguments and run the selected mode."""
    parser = argparse.ArgumentParser(description="Check Swift identifiers against glossary.toml.")
    modes = parser.add_subparsers(dest="mode", required=True)

    modes.add_parser("check", help="fail when a file exceeds its recorded budget")

    listing = modes.add_parser("list", help="print the findings")
    listing.add_argument("path", nargs="?", type=Path, help="limit to a file or directory")
    listing.add_argument("--statistics", action="store_true", help="tally per rejected spelling")

    update = modes.add_parser("update", help="rewrite the budget from today's counts")
    update.add_argument("--allow-raise", action="store_true", help="permit a count to grow")

    render = modes.add_parser("render", help="rewrite the generated sections of docs/GLOSSARY.md")
    render.add_argument("--check", action="store_true", help="verify instead of writing")

    sync = modes.add_parser("sync-lint", help="rewrite the generated custom_rules in .swiftlint.yml")
    sync.add_argument("--check", action="store_true", help="verify instead of writing")


    args = parser.parse_args(argv)
    glossary = load_glossary()

    if args.mode == "check":
        return mode_check(glossary)
    if args.mode == "list":
        return mode_list(glossary, args.path, args.statistics)
    if args.mode == "update":
        return mode_update(glossary, args.allow_raise)
    if args.mode == "render":
        return mode_render(glossary, args.check)
    return mode_sync_lint(glossary, args.check)


if __name__ == "__main__":
    raise SystemExit(main())
